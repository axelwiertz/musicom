import os, math
from generators.schillinger import SchillingerGenerator

SECTION_GENERATORS = [(3, 2), (4, 3), (5, 3), (5, 2)]
SECTION_NAMES = ["I (G)", "V (D)", "vi (Em)", "IV (C)"]
SECTION_TICKS = 3840
CELL = 120                      # 16th-note resolution -> 32 cells / section
NCELL = SECTION_TICKS // CELL   # 32

def onsets_for(a, b):
    gen = SchillingerGenerator(generator_a=a, generator_b=b)
    durations = gen.generate_resultant()
    total_span = a * b
    base = SECTION_TICKS / total_span
    onsets = [0]
    for d in durations[:-1]:
        onsets.append(onsets[-1] + int(round(d * base)))
    note_durs = []
    for i in range(len(onsets)):
        if i + 1 < len(onsets):
            note_durs.append(onsets[i + 1] - onsets[i])
        else:
            note_durs.append(SECTION_TICKS - onsets[i])
    return onsets, note_durs

# Build a 32-cell per-section rhythm grid (█ onset, ░ rest)
rhythm_rows = {}
for s, (a, b) in enumerate(SECTION_GENERATORS):
    onsets, durs = onsets_for(a, b)
    cells = ["░"] * NCELL
    for on, dur in zip(onsets, durs):
        cs = int(round(on / CELL))
        ce = max(cs + 1, int(round((on + dur) / CELL)))
        for idx in range(cs, min(ce, NCELL)):
            cells[idx] = "█"
    rhythm_rows[SECTION_NAMES[s]] = ("".join(cells), len(onsets), onsets, durs)

# Pitch DNA: raw sine axis projection sample (Phase-1, pre-harmonic)
def raw_axis(n):
    scale = [67 + iv for iv in [0, 2, 4, 5, 7, 9, 11, 12]]
    out = []
    for i in range(n):
        idx = int(4 + 3 * math.sin(i * 0.8))
        idx = max(0, min(len(scale) - 1, idx % len(scale)))
        out.append(scale[idx])
    return out

