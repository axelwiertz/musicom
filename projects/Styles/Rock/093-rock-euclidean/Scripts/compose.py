# --- row 0 LEAD: Euclidean 16th lock (rotating cell) + scale-degree contour
for s in range(N_SECTIONS):
    k, n, unit = PATTERNS["lead"]
    evs = []
    raw = sorted((e for e in phase1.matrix.get_unit((0, s)).events
                  if e.pitch > 0), key=lambda e: e.start_tick)
    raw_mean = (float(np.mean([e.pitch for e in raw])) if raw else 76.0)
    lead_center = min(range(len(LEAD_POOL)),
                      key=lambda i: abs(LEAD_POOL[i] - raw_mean))
    gcount = 0
    for b in range(BARS_PER):
        t0 = b * BAR
        rot = (b + s) % 3                       # rotate the Euclidean cell
        ons, _ = euclid_onsets(k, n, unit, rot=rot)
        bar = s * BARS_PER + b
        deg = PROG_DEG[bar]
        tones = chord_tones(deg, LEAD_LO, LEAD_HI) or [degree_note(deg) + 24]
        for j, off in enumerate(ons):
            step = MOTIF_STEPS[(s * BARS_PER * 6 + gcount) % len(MOTIF_STEPS)]
            lead_center = max(0, min(len(LEAD_POOL) - 1, lead_center + step))
            p = LEAD_POOL[lead_center]
            qp = min(tones, key=lambda c: (abs(c - p), c))
            accent = 0 if off % 480 == 0 else (1 if off % 240 == 0 else 2)
            vel = (92, 82, 74)[accent]
            evs.append(MusicEvent(pitch=qp, volume=vel,
                                  start_tick=t0 + off, end_tick=t0 + off + 118))
            gcount += 1
    evs.sort(key=lambda e: e.start_tick)
    # voice leading: cap leaps > 10 semitones toward the nearest chord tone
    for i in range(1, len(evs)):
        if abs(evs[i].pitch - evs[i - 1].pitch) > 10:
            bar = s * BARS_PER + min(evs[i].start_tick // BAR, BARS_PER - 1)
            tones = chord_tones(PROG_DEG[bar], LEAD_LO, LEAD_HI)
            if tones:
                evs[i].pitch = min(tones, key=lambda c: (abs(c - evs[i - 1].pitch), c))
    for i in range(len(evs) - 1):               # monophonic legato
        if evs[i].end_tick > evs[i + 1].start_tick:
            evs[i].end_tick = evs[i + 1].start_tick
    phase2.set_unit(0, s, MusicUnit(events=evs))

