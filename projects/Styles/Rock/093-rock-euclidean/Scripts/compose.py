def raw_euclid_melody(seed, section_ticks, n_events, center0):
    """Raw draft: Euclidean intervals at a FRACTIONAL unit + an unwalked pitch.

    The interval list comes from `euclidian(k, n)`; the tick value of one step
    is solved from the section length so the pattern fills the span, then
    jittered per onset. The resulting unit is almost never a multiple of 120,
    so the raw draft is off-grid by construction.
    """
    r = np.random.default_rng(seed)
    k, n = P1_PAIRS[seed % len(P1_PAIRS)]
    ivs = euclidian(k, n)
    cycle_steps = sum(ivs)
    # steps needed to fill the section: unit = section / total_pattern_steps
    unit = section_ticks / float(cycle_steps * max(1, n_events / cycle_steps))
    evs = []
    tick = 0.0
    center = center0
    i = 0
    while len(evs) < n_events:
        d = ivs[i % len(ivs)]
        step = unit * d * (0.94 + 0.12 * r.random())   # jitter -> OFF-GRID
        dur = int(round(step)) - 47                    # gaps -> no legato lock
        dur = max(60, dur)
        if tick + step > section_ticks:
            break
        # raw, unquantized pitch walk (no scale, no chord, no harmony)
        p = center + r.choice([-5, -3, -2, -1, 1, 2, 3, 4, 7]) + \
            0.9 * r.normal(0, 1.0)
        p = max(55.0, min(96.0, p))
        vel = int(np.clip(66 + 24 * abs(np.sin(i * 1.13)), 50, 108))
        evs.append(MusicEvent(pitch=int(round(p)), volume=vel,
                              start_tick=int(round(tick)),
                              end_tick=int(round(tick)) + dur))
        tick += step
        center += r.normal(0.0, 0.9)
        i += 1
    return evs


