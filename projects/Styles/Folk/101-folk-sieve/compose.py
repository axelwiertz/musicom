# PHASE 1: Raw Generative Sieve Draft (Single Voice)
# ================================================================
def generate_phase1_raw():
    """Generates unquantized raw sieve walk:
    - Pitch selection directly from unbounded Xenakis sieve walk
    - Unquantized timing with micro-timing fluctuations (off-grid)
    - Single voice (Fiddle)
    - Zero-drift boundary invariant guaranteed per section
    """
    composer_p1 = UnitMatrixComposer(bpm=BPM, ticks_per_beat=TPB, beats_per_bar=BEATS_PER_BAR)
    composer_p1.create_matrix(num_voices=1, num_sections=N_SECTIONS)
    composer_p1.add_voice("Raw_Fiddle", program=VIOLIN.midi_program, channel=0)
    
    for s_idx, s_name in enumerate(SECTIONS):
        composer_p1.add_section(s_name, bars=BARS_PER_SECTION)
        events = []
        
        # Raw generative walk: generate events driven by sieve indices
        # Step interval approximately 235 ticks (intentionally off 120/240 grid)
        curr_tick = 35  # initial offset
        sieve_idx = s_idx * 17
        
        while curr_tick < SECTION_TICKS - 300:
            # Advance sieve until match
            while not is_in_pitch_sieve(sieve_idx):
                sieve_idx += 1
            
            # Map sieve index to raw pitch centered around D4 (62)
            # Add continuous non-integer pitch offset simulation
            raw_pitch = 62 + (sieve_idx % 24) - 5
            raw_pitch = int(np.clip(raw_pitch, 55, 86))
            
            dur = int(rng.uniform(160, 290))
            end_t = min(curr_tick + dur, SECTION_TICKS - 50)
            vel = int(rng.integers(70, 95))
            
            events.append(MusicEvent(
                pitch=raw_pitch,
                volume=vel,
                start_tick=curr_tick,
                end_tick=end_t
            ))
            
            # Non-grid advance (e.g. 235 +- 30 ticks)
            advance = int(235 + rng.integers(-25, 25))
            curr_tick += advance
            sieve_idx += 1
            
        # Terminal landmark for zero-drift
        events.append(MusicEvent(
            pitch=0, volume=0,
            start_tick=SECTION_TICKS - 1,
            end_tick=SECTION_TICKS
        ))
        
        unit = MusicUnit(events=events)
        composer_p1.fill_voice_section("Raw_Fiddle", s_name, unit)
        
    ok, msg = composer_p1.validate()
    assert ok, f"Phase 1 validate failed: {msg}"
    
    p1_path = os.path.join(MIDI_DIR, "101-folk-sieve-phase1.mid")
    composer_p1.to_midi(p1_path)
    assert os.path.getsize(p1_path) > 40, "Phase 1 MIDI empty"
    print(f"Phase 1 MIDI written: {p1_path} ({os.path.getsize(p1_path)} bytes)")
    
    # Provenance for Phase 1
    write_provenance(
        p1_path,
        classification=AI_ASSISTED,
        generator="musicom.workflows.unitmatrix_composer",
        parameters={
            "project": "101-folk-sieve",
            "phase": 1,
            "style": "Folk",
            "method": "025 Xenakis Sieve Theory",
            "layer": "concrete",
            "raw_timing": "unquantized",
            "seed": SEED
        }
    )
    return p1_path

