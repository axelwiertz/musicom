# PHASE 2: Musicom Rules Post-Processing & Multi-Voice Arrangement
# ================================================================
def generate_phase2_composition():
    """Generates full multi-voice composition with musicom rules:
    - 16th-grid quantization (120 ticks)
    - Diatonic D Dorian + strict bar chord-tone quantization
    - Authentic Folk arrangement: Fiddle, Whistle, Acoustic Guitar, Double Bass, Bodhran/Drums
    - Strict zero-drift enforcement across all voices
    """
    composer_p2 = UnitMatrixComposer(bpm=BPM, ticks_per_beat=TPB, beats_per_bar=BEATS_PER_BAR)
    composer_p2.create_matrix(num_voices=5, num_sections=N_SECTIONS)
    
    composer_p2.add_voice("Fiddle", program=VIOLIN.midi_program, channel=0)
    composer_p2.add_voice("Whistle", program=FLUTE.midi_program, channel=1)
    composer_p2.add_voice("Guitar", program=ACOUSTIC_GUITAR.midi_program, channel=2)
    composer_p2.add_voice("Bass", program=DOUBLE_BASS.midi_program, channel=3)
    composer_p2.add_voice("Drums", program=0, channel=9)
    
    for s_idx, s_name in enumerate(SECTIONS):
        composer_p2.add_section(s_name, bars=BARS_PER_SECTION)
        
        fiddle_events = []
        whistle_events = []
        guitar_events = []
        bass_events = []
        drum_events = []
        
        for bar_in_sec in range(BARS_PER_SECTION):
            bar_start = bar_in_sec * BAR_TICKS
            bar_chord_name = get_bar_chord(s_idx, bar_in_sec)
            c_pcs = CHORD_PCS[bar_chord_name]
            
            # --- 1. Voice 1: Fiddle (Lead) ---
            # Driven by Xenakis rhythmic sieve on 16th subdivisions,
            # pitches derived from sieve sequence and quantized to chord tones
            sieve_counter = (s_idx * 16) + (bar_in_sec * 7)
            for step in range(16):
                t_onset = bar_start + (step * GRID16)
                # Check rhythmic sieve match or primary reel beat
                is_sieve_active = is_in_rhythm_sieve(step)
                # In Theme A and B, lead is dense (reel runs); in Intro/Breakdown slightly more spaced
                play_step = is_sieve_active
                if s_name in ("Theme_A", "Theme_A_Var") and (step % 2 == 0):
                    play_step = True  # continuous driving reel feel
                elif s_name == "Intro" and (step % 4 != 0 and not is_sieve_active):
                    play_step = False
                elif s_name == "Breakdown" and (step % 4 != 0):
                    play_step = False
                    
                if play_step:
                    # Advance pitch sieve
                    while not is_in_pitch_sieve(sieve_counter):
                        sieve_counter += 1
                    raw_pc = (sieve_counter % 12)
                    raw_pitch = 62 + raw_pc + ((sieve_counter // 12) % 2) * 12
                    # Quantize to chord tones of active bar within violin range (62-86)
                    chord_pitch = quantize_to_chord(raw_pitch, c_pcs, target_octave=5, min_pitch=62, max_pitch=86)
                    
                    # Onset on grid, duration 16th (100 ticks + 20 gap)
                    dur = 100
                    vel = 96 if (step % 4 == 0) else 82
                    fiddle_events.append(MusicEvent(
                        pitch=chord_pitch,
                        volume=vel,
                        start_tick=t_onset,
                        end_tick=t_onset + dur
                    ))
                    sieve_counter += 1
                    
            # --- 2. Voice 2: Whistle (Countermelody) ---
            # Sustained lyrical phrases, playing on main downbeats and harmonic pivots
            # Active in Theme A, Theme B, Theme A Var, Outro
            if s_name in ("Theme_A", "Theme_B", "Theme_A_Var", "Outro"):
                whistle_steps = [0, 4, 8, 12] if s_name != "Theme_B" else [0, 6, 8, 14]
                for w_idx, step in enumerate(whistle_steps):
                    t_onset = bar_start + (step * GRID16)
                    # Select upper register chord tone
                    base_p = 74 + (w_idx * 3)  # high whistle register
                    w_pitch = quantize_to_chord(base_p, c_pcs, target_octave=6, min_pitch=69, max_pitch=93)
                    dur = 3 * GRID16  # sustained note
                    whistle_events.append(MusicEvent(
                        pitch=w_pitch,
                        volume=88 if step == 0 else 76,
                        start_tick=t_onset,
                        end_tick=min(t_onset + dur, bar_start + BAR_TICKS)
                    ))
                    
            # --- 3. Voice 3: Acoustic Guitar (Folk Rhythmic Strum) ---
            # Classic folk reel boom-chick rhythm:
            # Beat 1 (0): low bass note of chord
            # Beat 2 (480): upbeat chord strum
            # Beat 3 (960): alternate chord tone
            # Beat 4 (1440): upbeat chord strum
            # Plus 8th-note pushes at 720 and 1680 ticks
            guitar_strum_ticks = [
                (0, 0.9, True),     # bass root
                (240, 0.7, False),   # light strum
                (480, 0.85, False),  # full strum
                (720, 0.7, False),   # pickup
                (960, 0.88, True),   # bass fifth/third
                (1200, 0.7, False),  # light strum
                (1440, 0.85, False), # full strum
                (1680, 0.75, False)  # pickup
            ]
            for tick_off, v_scale, is_bass_pulse in guitar_strum_ticks:
                t_onset = bar_start + tick_off
                if is_bass_pulse:
                    # Single bass root note on guitar
                    root_pitch = quantize_to_chord(45, c_pcs, target_octave=3)
                    guitar_events.append(MusicEvent(
                        pitch=root_pitch,
                        volume=int(85 * v_scale),
                        start_tick=t_onset,
                        end_tick=t_onset + 200
                    ))
                else:
                    # 3-note triad strum
                    # Voicing in octave 4
                    sorted_pcs = sorted(list(c_pcs))
                    for i, pc in enumerate(sorted_pcs):
                        p = 48 + pc + (12 if pc < 5 else 0)
                        guitar_events.append(MusicEvent(
                            pitch=p,
                            volume=int(75 * v_scale),
                            start_tick=t_onset,
                            end_tick=t_onset + 180
                        ))
                        
            # --- 4. Voice 4: Double Bass ---
            # Root - Fifth dance pattern locking to beats 1 and 3 (0 and 960 ticks)
            # With 8th note walk on beat 4 (1440 ticks)
            bass_steps = [
                (0, 38, 90, 420),      # Beat 1 (Downbeat root)
                (480, 38, 70, 200),    # Beat 2 bounce
                (960, 45, 88, 420),    # Beat 3 (Fifth)
                (1440, 40, 75, 200),   # Beat 4 (Walk tone)
                (1680, 43, 72, 200)    # Beat 4& (Approach tone)
            ]
            for tick_off, nominal_p, vel, dur in bass_steps:
                t_onset = bar_start + tick_off
                b_pitch = quantize_to_chord(nominal_p, c_pcs, target_octave=2, min_pitch=28, max_pitch=55)
                bass_events.append(MusicEvent(
                    pitch=b_pitch,
                    volume=vel,
                    start_tick=t_onset,
                    end_tick=t_onset + dur
                ))
                
            # --- 5. Voice 5: Drums / Bodhrán (Percussion ch 9) ---
            # Bodhrán-style kick pulse on beats 1 and 3 (MIDI 36)
            # Snare/Rim click on beats 2 and 4 (MIDI 38/37)
            # Shaker/Tambourine/HiHat 8th-note pulse (MIDI 42)
            # Accents governed by Xenakis rhythm sieve
            for step in range(16):
                t_onset = bar_start + (step * GRID16)
                # HiHat on every 8th note (even 16ths)
                if step % 2 == 0:
                    hh_vel = 80 if (step % 4 == 0) else 65
                    drum_events.append(MusicEvent(
                        pitch=42, volume=hh_vel,
                        start_tick=t_onset, end_tick=t_onset + 60
                    ))
                # Bodhrán deep thump on beat 1 and 3
                if step in (0, 8):
                    drum_events.append(MusicEvent(
                        pitch=36, volume=100 if step == 0 else 90,
                        start_tick=t_onset, end_tick=t_onset + 100
                    ))
                # Tap on beat 2 and 4
                if step in (4, 12):
                    drum_events.append(MusicEvent(
                        pitch=38, volume=88,
                        start_tick=t_onset, end_tick=t_onset + 90
                    ))
                # Sieve accent hit on crash/tambourine if in rhythm sieve
                if is_in_rhythm_sieve(step) and step not in (0, 4, 8, 12):
                    drum_events.append(MusicEvent(
                        pitch=54, volume=72,  # Tambourine
                        start_tick=t_onset, end_tick=t_onset + 70
                    ))
                    
        # --- Zero-drift Terminal Landmark Enforcement ---
        def seal_voice_events(ev_list):
            # Sort events chronologically
            ev_list.sort(key=lambda e: (e.start_tick, e.end_tick))
            # Append zero-drift boundary landmark
            ev_list.append(MusicEvent(
                pitch=0, volume=0,
                start_tick=SECTION_TICKS - 1,
                end_tick=SECTION_TICKS
            ))
            return MusicUnit(events=ev_list)
            
        composer_p2.fill_voice_section("Fiddle", s_name, seal_voice_events(fiddle_events))
        composer_p2.fill_voice_section("Whistle", s_name, seal_voice_events(whistle_events))
        composer_p2.fill_voice_section("Guitar", s_name, seal_voice_events(guitar_events))
        composer_p2.fill_voice_section("Bass", s_name, seal_voice_events(bass_events))
        composer_p2.fill_voice_section("Drums", s_name, seal_voice_events(drum_events))
        
    ok, msg = composer_p2.validate()
    assert ok, f"Phase 2 validate failed: {msg}"
    
    p2_path = os.path.join(MIDI_DIR, "101-folk-sieve.mid")
    composer_p2.to_midi(p2_path)
    assert os.path.getsize(p2_path) > 40, "Phase 2 MIDI empty"
    print(f"Phase 2 MIDI written: {p2_path} ({os.path.getsize(p2_path)} bytes)")

    # Write Grid Visualization
    grid_path = os.path.join(ANALYSIS_DIR, "grid_visualization.txt")
    write_grid_visualization(
        composer_p2.matrix,
        grid_path,
        ticks_per_character=240,
        voice_names=["Fiddle", "Whistle", "Guitar", "Bass", "Drums"],
        bpm=BPM
    )
    print(f"Grid visualization written: {grid_path} ({os.path.getsize(grid_path)} bytes)")
    
    # Provenance for Phase 2
    write_provenance(
        p2_path,
        classification=AI_ASSISTED,
        generator="musicom.workflows.unitmatrix_composer",
        parameters={
            "project": "101-folk-sieve",
            "phase": 2,
            "style": "Folk",
            "method": "025 Xenakis Sieve Theory",
            "layer": "concrete",
            "quantization": "16th-grid (120 ticks)",
            "key": "D Dorian",
            "bpm": BPM,
            "seed": SEED
        }
    )
    return p2_path

