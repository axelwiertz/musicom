# Chord progression per section (4 bars per section):
# D Dorian modal folk changes:
# 0: Intro:       Dm | Dm | C  | Dm
# 1: Theme A:     Dm | C  | G  | Dm
# 2: Theme B:     F  | C  | Dm | Am
# 3: Breakdown:   G  | C  | Dm | Dm
# 4: Theme A Var: Dm | C  | G  | Dm
# 5: Outro:       Dm | C  | Dm | Dm
SECTION_CHORDS = {
    0: ["Dm", "Dm", "C", "Dm"],
    1: ["Dm", "C", "G", "Dm"],
    2: ["F", "C", "Dm", "Am"],
    3: ["G", "C", "Dm", "Dm"],
    4: ["Dm", "C", "G", "Dm"],
    5: ["Dm", "C", "Dm", "Dm"],
}

CHORD_PCS = {
    "Dm": {2, 5, 9},        # D, F, A
    "C":  {0, 4, 7},        # C, E, G
    "G":  {7, 11, 2},       # G, B, D
    "F":  {5, 9, 0},        # F, A, C
    "Am": {9, 0, 4},        # A, C, E
}

def get_bar_chord(sec_idx, bar_in_sec):
    return SECTION_CHORDS[sec_idx][bar_in_sec]

# ---------------------------------------------------------------- Method 025: Xenakis Sieve Theory
# Xenakis Sieve formula:
# Logical combination of congruence classes (residual classes modulo integer moduli).
# Sieve 1 (Pitch selection):
# Let A = { n in Z : n mod 3 in {0, 2} }
# Let B = { n in Z : n mod 4 in {0, 1, 2} }
# S_pitch = A \cap B over period lcm(3, 4) = 12
# S_pitch offsets mod 12: {0, 2, 5, 9, 11} -> Pentatonic/modal core within D Dorian!
SIEVE_PITCH_A_MOD, SIEVE_PITCH_A_RES = 3, (0, 2)
SIEVE_PITCH_B_MOD, SIEVE_PITCH_B_RES = 4, (0, 1, 2)

def is_in_pitch_sieve(n):
    return (n % SIEVE_PITCH_A_MOD in SIEVE_PITCH_A_RES) and (n % SIEVE_PITCH_B_MOD in SIEVE_PITCH_B_RES)

SIEVE_PITCH_RESIDUES = [n for n in range(12) if is_in_pitch_sieve(n)]
print(f"Sieve Pitch Residues (mod 12): {SIEVE_PITCH_RESIDUES}")

# Sieve 2 (Rhythmic sieve):
# Grid pulses over 16 subdivisions per bar.
# Let R_A = { t in Z : t mod 4 in {0, 2, 3} }
# Let R_B = { t in Z : t mod 8 in {0, 1, 3, 4, 6} }
# S_rhythm = R_A \cap R_B provides characteristic syncopated folk reel accents
def is_in_rhythm_sieve(step):
    r_a = (step % 4) in (0, 2, 3)
    r_b = (step % 8) in (0, 1, 3, 4, 6)
    return r_a and r_b

SIEVE_RHYTHM_STEPS = [s for s in range(16) if is_in_rhythm_sieve(s)]
print(f"Sieve Rhythm Steps (in 16-step bar): {SIEVE_RHYTHM_STEPS}")

# ---------------------------------------------------------------- Helper: Quantization
def quantize_to_chord(pitch, chord_pcs, target_octave=4, min_pitch=None, max_pitch=None):
    """Finds nearest pitch whose pitch-class is in chord_pcs, optionally bounded."""
    candidates = []
    for octv in range(target_octave - 3, target_octave + 4):
        for pc in chord_pcs:
            p = octv * 12 + pc
            if min_pitch is not None and p < min_pitch:
                continue
            if max_pitch is not None and p > max_pitch:
                continue
            candidates.append(p)
    if not candidates:
        # Fallback without bounds if range too narrow
        for octv in range(target_octave - 2, target_octave + 3):
            for pc in chord_pcs:
                candidates.append(octv * 12 + pc)
    return min(candidates, key=lambda c: (abs(c - pitch), c))

