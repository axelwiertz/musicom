# ---------------------------------------------------------------- Grid & Timing
BPM = 116  # Lively folk dance tempo
TPB = 480  # Ticks per beat (quarter note)
BEATS_PER_BAR = 4
GRID16 = 120  # 16th note = 120 ticks
GRID8 = 240   # 8th note = 240 ticks
BAR_TICKS = TPB * BEATS_PER_BAR  # 1920 ticks

SECTIONS = ["Intro", "Theme_A", "Theme_B", "Breakdown", "Theme_A_Var", "Outro"]
BARS_PER_SECTION = 4
