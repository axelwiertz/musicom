def baroque_fitness(genome):
    """Fitness for a genetic genome: reward Bach-style conjunct motion.
    Genome layout is the library's 18-bit event: pitch bits (0..5) per event
    decode to a RELATIVE interval; onset/dur/vel bits are irrelevant here.
    Consecutive stepwise intervals (streams) are rewarded super-linearly;
    big leaps are penalized."""
    s = 0
    n_ev = len(genome) // 18
    run = 0
    for i in range(n_ev):
        base = i * 18
        chunk = sum(bit * pow(2, j) for j, bit in enumerate(genome[base:base + 6]))
        interval = chunk % 24 - 12        # -12..+11 semitones
        if abs(interval) in (1, 2):       # stepwise
            run += 1
            s += 3 + run                  # streaks = Bach-style streams
        elif abs(interval) in (3, 4, 5):  # small leap
            run = 0
            s += 1
        elif abs(interval) == 0:          # repeat
            run = 0
            s += 0
        else:                             # large leap
            run = 0
            s -= 2
    return max(1, s)


